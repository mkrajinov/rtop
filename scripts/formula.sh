#!/bin/sh
# Prints the Homebrew formula for release VERSION (no leading v), with the checksums of
# the four archives from CHECKSUMS (sha256sum output; default dist/checksums.txt).
# release.yml writes it to Formula/rtop.rb in mkrajinov/homebrew-tap.
#
#   ./scripts/formula.sh 0.1.0 dist/checksums.txt > rtop.rb
set -eu
v=${1:?usage: formula.sh VERSION [CHECKSUMS]}
sums=${2:-dist/checksums.txt}
url="https://github.com/mkrajinov/rtop/releases/download/v$v"

# sha256 of rtop_<version>_<os>_<arch>.tar.gz; fails when the archive is missing.
sha() {
	s=$(awk -v f="rtop_${v}_$1.tar.gz" '$2 == f || $2 == "*" f { print $1 }' "$sums")
	[ -n "$s" ] || { echo "formula.sh: no checksum for rtop_${v}_$1.tar.gz in $sums" >&2; exit 1; }
	echo "$s"
}
darwin_arm64=$(sha darwin_arm64)
darwin_amd64=$(sha darwin_amd64)
linux_arm64=$(sha linux_arm64)
linux_amd64=$(sha linux_amd64)

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/formula.sh in mkrajinov/rtop. DO NOT EDIT.
class Rtop < Formula
  desc "Top, with receipts: process explorer that shows where every number comes from"
  homepage "https://github.com/mkrajinov/rtop"
  version "$v"

  on_macos do
    on_arm do
      url "$url/rtop_${v}_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$url/rtop_${v}_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$url/rtop_${v}_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$url/rtop_${v}_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "rtop"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/rtop --version")
  end
end
EOF
